import type { ShrinkResult } from "../core/types.js";
import { formatCount, formatDuration, formatPercent, formatSize } from "../utils/format.js";
import { toJsonString } from "../utils/json-safe.js";
import { VERSION } from "../version.js";
import { diffValues, formatDiff } from "./diff.js";
import { redactDiffEntries, redactValue, type RedactOptions } from "./redact.js";

export interface MarkdownReportOptions {
  /** Where the input came from (file path, label). */
  inputSource?: string;
  /** Include the structural diff section. Default: `true`. */
  includeDiff?: boolean;
  /** Include the configuration section. Default: `true`. */
  includeConfig?: boolean;
  /** Cap on diff lines. Default: 50. */
  maxDiffEntries?: number;
  /** Cap on history rows. Default: 20. */
  maxHistoryEntries?: number;
  redact?: RedactOptions;
}

const STATUS_TEXT: Record<ShrinkResult<unknown>["status"], string> = {
  completed: "Completed — no further reduction found",
  "limit-reached": "Stopped early — an execution limit was reached",
  cancelled: "Cancelled — result is the best input found so far",
  unstable: "Completed, but the predicate behaved inconsistently",
  failed: "Failed — the target condition could not be established",
};

/**
 * Human-readable report suitable for a PR comment or a bug ticket.
 * Contains no absolute paths unless the caller passes one as `inputSource`.
 */
export function createMarkdownReport<T>(
  result: ShrinkResult<T>,
  options: MarkdownReportOptions = {},
): string {
  const lines: string[] = [];
  const stats = result.stats;
  const minimalInput = redactValue(result.minimalInput, options.redact);

  lines.push("# ShrinkJS Reduction Report", "");
  lines.push(`Generated by \`@shrinkjs/core\` v${VERSION}.`, "");

  lines.push("## Summary", "");
  lines.push("| Field | Value |", "| --- | --- |");
  lines.push(`| Status | ${STATUS_TEXT[result.status]} |`);
  lines.push(
    `| Reduced input | ${result.minimality === "local" ? "locally minimal (for the enabled reducers)" : "not proven minimal"} |`,
  );
  lines.push(
    `| Original size | ${formatSize(stats.originalSize)} (${formatCount(stats.originalSize)} chars) |`,
  );
  lines.push(`| Reduced size | ${formatSize(stats.finalSize)} (${formatCount(stats.finalSize)} chars) |`);
  lines.push(`| Reduction | ${formatPercent(stats.reductionPercent)} |`);
  lines.push(`| Predicate evaluations | ${formatCount(stats.evaluations)} |`);
  lines.push(`| Accepted reductions | ${formatCount(stats.successfulReductions)} |`);
  lines.push(`| Rejected candidates | ${formatCount(stats.rejectedCandidates)} |`);
  lines.push(`| Duration | ${formatDuration(stats.durationMs)} |`);
  if (stats.limitReached) lines.push(`| Limit reached | \`${stats.limitReached}\` |`);
  if (result.signature !== null) lines.push(`| Failure signature | \`${result.signature}\` |`);
  if (stats.verification.performed) {
    lines.push(`| Fresh-copy verification | ${stats.verification.preserved ? "passed" : "failed"} |`);
  }
  lines.push("");

  if (result.error) {
    lines.push("## Error", "", `**${result.error.code}** — ${result.error.message}`, "");
  }

  lines.push("## Minimal reproduction", "");
  lines.push("```json");
  lines.push(toJsonString(minimalInput, 2));
  lines.push("```", "");

  if (options.includeDiff !== false) {
    const entries = diffValues(result.originalInput, result.minimalInput, {
      maxEntries: options.maxDiffEntries ?? 50,
    });
    lines.push("## Structural diff", "");
    lines.push("```diff");
    lines.push(formatDiff(options.redact ? redactDiffEntries(entries, options.redact) : entries));
    lines.push("```", "");
  }

  lines.push("## Statistics", "");
  lines.push("| Strategy | Attempts | Accepted | Rejected |", "| --- | --- | --- | --- |");
  const strategies = Object.entries(stats.strategies).sort((a, b) => b[1].attempts - a[1].attempts);
  if (strategies.length === 0) {
    lines.push("| _none_ | 0 | 0 | 0 |");
  } else {
    for (const [name, stat] of strategies) {
      lines.push(`| \`${name}\` | ${stat.attempts} | ${stat.accepted} | ${stat.rejected} |`);
    }
  }
  lines.push("");
  lines.push(
    `Cache hits: ${formatCount(stats.cacheHits)} · Predicate errors: ${formatCount(stats.predicateErrors)} · Timeouts: ${formatCount(stats.timeouts)} · Unstable candidates: ${formatCount(stats.unstableCandidates)} · Signature mismatches: ${formatCount(stats.signatureMismatches)}`,
    "",
  );

  if (options.includeConfig !== false) {
    lines.push("## Configuration", "");
    lines.push("```json");
    lines.push(JSON.stringify(result.config, null, 2));
    lines.push("```", "");
  }

  if (result.history && result.history.length > 0) {
    const max = options.maxHistoryEntries ?? 20;
    lines.push("## History", "");
    lines.push("| # | Strategy | Path | Outcome | Before | After |", "| --- | --- | --- | --- | --- | --- |");
    for (const entry of result.history.slice(-max)) {
      lines.push(
        `| ${entry.step} | \`${entry.strategy}\` | \`${entry.path}\` | ${entry.outcome} | ${entry.sizeBefore} | ${entry.sizeAfter} |`,
      );
    }
    lines.push("");
  }

  if (result.warnings.length > 0) {
    lines.push("## Warnings", "");
    for (const warning of result.warnings) lines.push(`- ${warning}`);
    lines.push("");
  }

  lines.push("## Limitations", "");
  lines.push(
    "- ShrinkJS searches for *smaller* inputs; it does not prove mathematical minimality.",
    '- `minimality: local` means "no candidate from the enabled reducers was accepted for the final input".',
    "- The predicate decides everything: if it accepts a non-reproducing input, the result inherits that mistake.",
    '- Sizes are counts of characters in a compact representation (see README, "Measuring size").',
    "",
  );

  return lines.join("\n");
}
